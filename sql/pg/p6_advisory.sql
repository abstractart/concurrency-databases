-- ============================================================
-- P6. Advisory-блокировки: мьютекс, не привязанный к строкам
-- PostgreSQL. Два окна psql.
-- pg_advisory_lock — уровень СЕССИИ: живёт до pg_advisory_unlock
-- или до конца соединения, commit/rollback на неё не влияют.
-- ============================================================

-- ── ТЕРМИНАЛ 1 ─────────────────────────────────────────────
SELECT pg_advisory_lock(42);      -- захватили «критическую секцию»
SELECT pg_sleep(5);               -- долгая работа

-- ── ТЕРМИНАЛ 2 (параллельно с Т1) ──────────────────────────
SELECT pg_try_advisory_lock(42);  -- f: ключ 42 занят, ждать не будем
SELECT pg_advisory_lock(42);      -- 🔒 висит, пока Т1 не отпустит
-- (после отпускания в Т1 этот SELECT мгновенно вернётся)

-- ── ТЕРМИНАЛ 1 (после сна) ─────────────────────────────────
SELECT pg_advisory_unlock(42);    -- → Т2 немедленно входит в секцию

-- ── ТЕРМИНАЛ 2 (когда вошёл) ───────────────────────────────
SELECT pg_advisory_unlock(42);

-- Замечание: try_lock под ДРУГИМ ключом не мешает:
SELECT pg_try_advisory_lock(43);  -- t: ключи независимы
SELECT pg_advisory_unlock(43);
