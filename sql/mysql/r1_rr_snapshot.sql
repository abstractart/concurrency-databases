-- ============================================================
-- R1. REPEATABLE READ: снапшот и повторяемое чтение
-- MySQL 8 (RR — уровень по умолчанию). Два окна mysql.
-- ============================================================

-- ── ТЕРМИНАЛ 1 ─────────────────────────────────────────────
SET SESSION TRANSACTION ISOLATION LEVEL REPEATABLE READ;  -- дефолт, для наглядности
BEGIN;
SELECT balance FROM accounts WHERE id = 1;             -- 1000.00

-- ── ТЕРМИНАЛ 2 (между чтениями Т1) ─────────────────────────
BEGIN;
UPDATE accounts SET balance = balance - 300 WHERE id = 1;
COMMIT;                                                -- зафиксировали 700.00

-- ── ТЕРМИНАЛ 1 снова ───────────────────────────────────────
SELECT balance FROM accounts WHERE id = 1;             -- СНОВА 1000.00!
-- Повторяемое чтение: транзакция видит свой снапшот, чужой commit не виден.

COMMIT;                                                -- конец транзакции
SELECT balance FROM accounts WHERE id = 1;             -- теперь 700.00:
-- новая транзакция → новый снапшот.
