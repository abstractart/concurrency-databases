-- ============================================================
-- O3. SERIALIZABLE + повтор (в MySQL это блокировки, не SSI!)
-- MySQL 8. Два окна mysql, блоки запускаются ПАРАЛЛЕЛЬНО.
-- ============================================================

-- ── ТЕРМИНАЛ 1 и ТЕРМИНАЛ 2 — одинаковый код ───────────────
SET SESSION TRANSACTION ISOLATION LEVEL SERIALIZABLE;
BEGIN;
SELECT balance FROM accounts WHERE id = 1;             -- обычный SELECT получает
                                                       -- shared lock (= FOR SHARE)!
                                                       -- обе увидят 1000.00
UPDATE accounts SET balance = 1000 - 100 WHERE id = 1;
-- Обе транзакции держат S-блокировку и ждут X-блокировку друг друга:
-- InnoDB детектирует deadlock. ОДНА из них получит:
-- ERROR 1213 (40001): Deadlock found when trying to get lock;
-- try restarting transaction
-- (а если deadlock-детект отключён — вторая дождётся 1205 Lock wait timeout)
COMMIT;                                                -- выжившая фиксируется

-- ── Обработка ──────────────────────────────────────────────
-- Жертва (1213/1205): ROLLBACK; и повторить ВСЮ транзакцию заново.
-- При повторе её SELECT подождёт X-блокировку соседа и прочитает
-- актуальное значение — конфликта больше не будет.

-- ── Проверка ───────────────────────────────────────────────
SELECT balance FROM accounts WHERE id = 1;             -- итог корректен

-- Вывод: в MySQL SERIALIZABLE — «наполовину пессимистичная» стратегия:
-- конфликт предотвращается блокировками, но всё равно требует ретрая (1213/1205).
