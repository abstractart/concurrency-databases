-- ============================================================
-- O2. Оптимистичная блокировка через updated_at (без version)
-- MySQL 8. Аналог O1, «версией» служит метка времени.
-- ============================================================

BEGIN;
SELECT balance, updated_at FROM accounts WHERE id = 1; -- запомнили метку
-- напр.: 2026-01-01 12:00:00.000000  (TIMESTAMP(6) хранит микросекунды)

UPDATE accounts
   SET balance    = 1000 - 100,
       updated_at = CURRENT_TIMESTAMP(6) -- (6): без этого MySQL усечёт до секунд
 WHERE id = 1
   AND updated_at = '2026-01-01 12:00:00.000000';  -- ← подставьте ЗНАЧЕНИЕ
                                                   --    из предыдущего SELECT
-- «0 rows affected» = кто-то записал после нашего чтения → ROLLBACK и повтор.
COMMIT;

-- Замечания (почему version обычно надёжнее):
--   * две записи в одну микросекунду возможны;
--   * метка меняется и «побочными» UPDATE, что даёт ложные конфликты.
