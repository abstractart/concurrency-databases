-- ============================================================
-- O2. Оптимистичная блокировка через updated_at (без version)
-- PostgreSQL. Аналог O1, «версией» служит метка времени.
-- ============================================================

BEGIN;
SELECT balance, updated_at FROM accounts WHERE id = 1; -- запомнили метку

UPDATE accounts
   SET balance    = 1000 - 100,
       updated_at = CURRENT_TIMESTAMP
 WHERE id = 1
   AND updated_at = '2026-01-01 12:00:00.000000';  -- ← подставьте ЗНАЧЕНИЕ
                                                   --    из предыдущего SELECT
-- «UPDATE 0» = кто-то записал после нашего чтения → ROLLBACK и повтор.
COMMIT;

-- Замечания (почему version обычно надёжнее):
--   * точность TIMESTAMP микросекундная, но две записи в один тик возможны;
--   * метка меняется и «побочными» UPDATE (например, касательными полей),
--     что даёт ложные конфликты.
