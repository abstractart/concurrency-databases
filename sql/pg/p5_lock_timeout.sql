-- ── ТЕРМИНАЛ 1 ─────────────────────────────────────────────
BEGIN;
SELECT balance FROM accounts WHERE id = 1 FOR UPDATE;  -- держим строку
SELECT pg_sleep(5);                                    -- 5 секунд «работы»

-- ── ТЕРМИНАЛ 2 (пока Т1 спит) ──────────────────────────────
SET lock_timeout = '2s';                               -- не ждать дольше 2 с
BEGIN;
SELECT balance FROM accounts WHERE id = 1 FOR UPDATE;
-- через 2 секунды:
-- ERROR:  canceling statement due to lock request timeout (SQLSTATE 55P03)
ROLLBACK;                                              -- вежливо освобождаемся

-- ── ТЕРМИНАЛ 1 (после сна) ─────────────────────────────────
COMMIT;                                                -- отпускаем строку

-- Смысл: приложение вместо 3 с висения получило ошибку через 2 с
-- и может вернуть пользователю «ресурс занят, попробуйте позже».
