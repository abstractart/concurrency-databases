-- ============================================================
-- O1. Оптимистичная блокировка: версионный столбец
-- MySQL 8. Блок можно выполнять в двух окнах ОДНОВРЕМЕННО.
-- ============================================================

-- ── Тело транзакции (одно и то же в обоих окнах) ───────────
BEGIN;
SELECT balance, version FROM accounts WHERE id = 1;    -- напр. 1000.00 | 0

UPDATE accounts
   SET balance    = 1000 - 100,          -- значение посчитано приложением
       version    = version + 1,
       updated_at = CURRENT_TIMESTAMP(6) -- (6): без этого MySQL усечёт до секунд
 WHERE id = 1
   AND version = 0;                      -- 🔑 проверка прочитанной версии

-- mysql-клиент покажет «Query OK, 1 row affected» (успех) или
-- «Query OK, 0 rows affected» (КОНФЛИКТ: сосед записал раньше).
-- При 0 строк:
ROLLBACK;                               -- и повторить всю транзакцию заново:
                                        -- SELECT вернёт уже новую версию.
-- При 1 строке:
COMMIT;

-- ── Проверка после гонки двух окон ─────────────────────────
SELECT id, balance, version FROM accounts WHERE id = 1;
-- version = 2 (обе транзакции в итоге применились, одна — со второй попытки)

