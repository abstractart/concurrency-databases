-- ============================================================
-- P6. GET_LOCK: именованный мьютекс, не привязанный к строкам
-- MySQL 8. Два окна mysql.
-- GET_LOCK — уровень СЕССИИ: живёт до RELEASE_LOCK или до конца
-- соединения; commit/rollback на неё не влияют.
-- ============================================================

-- ── ТЕРМИНАЛ 1 ─────────────────────────────────────────────
SELECT GET_LOCK('critical_section', 60);   -- 1 = захватили секцию
DO SLEEP(5);                               -- долгая работа

-- ── ТЕРМИНАЛ 2 (параллельно с Т1) ──────────────────────────
SELECT GET_LOCK('critical_section', 0);    -- 0 = занято, ждать не будем
SELECT GET_LOCK('critical_section', 60);   -- 🔒 висит, пока Т1 не отпустит
-- (после отпускания в Т1 этот SELECT мгновенно вернёт 1)

-- ── ТЕРМИНАЛ 1 (после сна) ─────────────────────────────────
SELECT RELEASE_LOCK('critical_section');   -- 1 → Т2 немедленно входит

-- ── ТЕРМИНАЛ 2 (когда вошёл) ───────────────────────────────
SELECT RELEASE_LOCK('critical_section');

-- Замечание: другое имя — независимый мьютекс:
SELECT GET_LOCK('other_section', 0);       -- 1
SELECT RELEASE_LOCK('other_section');
