-- ============================================================
-- R2. REPEATABLE READ при записи: MySQL НЕ защищает от lost update!
-- MySQL 8. Два окна mysql.
-- Сравните с PostgreSQL: там RR вернёт ошибку 40001.
-- ============================================================

-- ── ТЕРМИНАЛ 1 ─────────────────────────────────────────────
BEGIN;
SELECT balance FROM accounts WHERE id = 1;             -- 1000.00 (снапшот)
-- пауза: запустите Т2, затем продолжайте
UPDATE accounts SET balance = 1000 - 100 WHERE id = 1; -- записали 900.00
COMMIT;

-- ── ТЕРМИНАЛ 2 (начните ПАРАЛЛЕЛЬНО с Т1, до его COMMIT) ───
BEGIN;
SELECT balance FROM accounts WHERE id = 1;             -- тоже 1000.00 (снапшот)
UPDATE accounts SET balance = 1000 - 200 WHERE id = 1;
-- (выполните UPDATE после COMMIT в Т1) — пройдёт БЕЗ ошибок:
-- UPDATE делает «current read» по строке, но ЗНАЧЕНИЕ посчитано
-- из старого снапшота.
COMMIT;

-- ── Проверка ───────────────────────────────────────────────
SELECT balance FROM accounts WHERE id = 1;             -- 800 вместо 700!
-- Потерянное обновление, и СУБД об этом молчит.

-- ============================================================
-- ЛЕКАРСТВО 1: блокирующее чтение (FOR SHARE) — оно читает
-- АКТУАЛЬНОЕ значение и держит блокировку до конца транзакции.
-- ============================================================
BEGIN;
SELECT balance FROM accounts WHERE id = 1 FOR SHARE;   -- увидит актуальные 900.00
UPDATE accounts SET balance = 900 - 200 WHERE id = 1;  -- считаем от актуального
COMMIT;                                                -- корректные 700.00

