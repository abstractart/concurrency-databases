-- ============================================================
-- O3. SERIALIZABLE + повтор (настоящий SSI в PostgreSQL)
-- Два окна psql, блоки запускаются ПАРАЛЛЕЛЬНО.
-- ============================================================

-- ── ТЕРМИНАЛ 1 и ТЕРМИНАЛ 2 — одинаковый код ───────────────
BEGIN ISOLATION LEVEL SERIALIZABLE;
SELECT balance FROM accounts WHERE id = 1;             -- обе увидят 1000.00
UPDATE accounts SET balance = 1000 - 100 WHERE id = 1;
-- Одна из транзакций здесь (или на COMMIT ниже) получит:
-- ERROR:  could not serialize access due to concurrent update (SQLSTATE 40001)
COMMIT;                                                -- иногда ошибка возникает именно здесь

-- ── Обработка ──────────────────────────────────────────────
-- Упавшая транзакция: ROLLBACK; и повторить ВСЮ транзакцию заново.
-- При повторе конфликта уже не будет: снапшот свежий.
-- Выжившая транзакция: COMMIT.

-- ── Проверка ───────────────────────────────────────────────
SELECT balance FROM accounts WHERE id = 1;
-- Итог корректен: обе записи применились последовательно (после ретрая).

-- Это «чистая» оптимистика на уровне изоляции: PostgreSQL не блокирует
-- читателей, а обнаруживает опасную зависимость постфактум.
